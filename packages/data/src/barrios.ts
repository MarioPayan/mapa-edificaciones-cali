export interface Barrio {
  nombre: string
  /** '01'..'22', o '' si no se pudo determinar. */
  comuna: string
  lat: number
  lon: number
}

export const BARRIOS: readonly Barrio[] = FILAS.map(([nombre, comuna, lat, lon]) => ({
  nombre,
  comuna,
  lat,
  lon,
}))

/** Las 22 comunas de Cali, existan o no reportes en ellas. */
export const COMUNAS: readonly string[] = Array.from({ length: 22 }, (_, i) =>
  String(i + 1).padStart(2, '0'),
)

/** Barrios de una comuna; sin comuna, todos. Ordenados para un desplegable. */
export function barriosDeComuna(comuna: string): Barrio[] {
  const lista = comuna ? BARRIOS.filter((b) => b.comuna === comuna) : [...BARRIOS]
  return lista.sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'))
}

/** Busca un barrio por nombre, sin distinguir tildes ni mayúsculas. */
export function buscarBarrio(nombre: string): Barrio | undefined {
  const clave = normalizar(nombre)
  return BARRIOS.find((b) => normalizar(b.nombre) === clave)
}

function normalizar(valor: string): string {
  return valor
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
}
